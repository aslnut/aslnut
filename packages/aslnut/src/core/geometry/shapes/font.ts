const runs = new Map<string, [number, number, number][]>();
/** a character's lit runs: [first column, row from the top, last column + 1] */
export function glyphRuns(ch: string): [number, number, number][] {
  const c = ch.toUpperCase();
  let r = runs.get(c); if (r) return r;
  const g = G[c] ?? G[' ']!; r = [];
  for (let y = 0; y < 7; y++) for (let x = 0; x < 5; x++) {
    if (g[y * 5 + x] !== '#') continue;
    let e = x; while (e + 1 < 5 && g[y * 5 + e + 1] === '#') e++;
    r.push([x, y, e + 1]); x = e;
  }
  runs.set(c, r); return r;
}
/** a character the font has (else it is drawn blank) */
export const hasGlyph = (ch: string) => ch.toUpperCase() in G;
